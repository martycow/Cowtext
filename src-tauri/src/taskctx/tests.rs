/// A fixture graph: `rules` is globally pinned, `notes` is the task's own
/// seed (linked via `references` from `rules` so it renders visibly),
/// `imp` is transitively imported by `notes` (pulled into `node_ids` by the
/// closure even though `compile_preview`'s own renderer never surfaces a
/// non-pinned, non-referenced node in body text — §4.1 (node set) and §4.2
/// (rendered body) are deliberately not the same claim), and `extra` is
/// wired to nothing and must never appear.
fn golden_fixture(dir: &Path) -> String {
    touch(&dir.join("context/rules.md"), "rules body\n");
    touch(&dir.join("context/notes.md"), "notes body\n");
    touch(&dir.join("context/imp.md"), "imported body\n");
    touch(&dir.join("context/extra.md"), "extra body\n");
    write_tasklinks(dir, &[link("t-abc123", &["notes"])]);
    graph_json(
        "TestProj",
        &[
            node("rules", "Rules", "context/rules.md", true),
            node("notes", "Task Notes", "context/notes.md", false),
            node("imp", "Imported Detail", "context/imp.md", false),
            node("extra", "Unrelated", "context/extra.md", false),
        ],
        &[
            edge("e1", "rules", "notes", "references"),
            edge("e2", "notes", "imp", "imports"),
        ],
    )
}

#[test]
fn golden_task_context_body_and_node_ids_are_byte_exact() {
    let dir = temp_project("golden");
    let g = golden_fixture(&dir);

    let ctx = preview(&dir, "t-abc123", &g);

    assert!(ctx.errors.is_empty(), "unexpected errors: {:?}", ctx.errors);
    assert_eq!(ctx.node_ids, vec!["imp", "notes", "rules"]);
    let expected = "<!-- GENERATED BY COWTEXT — edit the graph or context/*.md, not this file -->\n\
\n\
# TestProj · task t-abc123 — agent context\n\
\n\
## Always read\n\
\n\
@context/rules.md\n\
\n\
## Read when relevant\n\
\n\
- When working on **Rules**, read @context/notes.md.\n";
    assert_eq!(ctx.body, expected);
    assert_eq!(ctx.bytes, expected.len());
    assert!(ctx.body.lines().next() == Some(crate::compile::GENERATED_HEADER));

    let _ = fs::remove_dir_all(&dir);
}

