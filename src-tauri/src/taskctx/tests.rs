#[test]
fn task_context_write_succeeds_at_exactly_the_documented_path_and_is_idempotent() {
    let dir = temp_project("write-ok");
    let content = format!("{}\nbody\n", crate::compile::GENERATED_HEADER);

    let rel1 = task_context_write(
        dir.to_string_lossy().into_owned(),
        "t-abc123".to_string(),
        content.clone(),
    )
    .unwrap();
    assert_eq!(rel1, ".cowtext/context/task-t-abc123.md");
    let on_disk = fs::read_to_string(dir.join(&rel1)).unwrap();
    assert_eq!(on_disk, content);

    // Re-running produces byte-identical content (§4.5 "idempotent, deterministic").
    let rel2 = task_context_write(
        dir.to_string_lossy().into_owned(),
        "t-abc123".to_string(),
        content.clone(),
    )
    .unwrap();
    assert_eq!(rel2, rel1);
    assert_eq!(fs::read_to_string(dir.join(&rel2)).unwrap(), content);
    let _ = fs::remove_dir_all(&dir);
}

