use super::*;
use serde_json::json;
use std::fs;
use std::path::{Path, PathBuf};

fn temp_project(tag: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("cowtext-taskctx-{tag}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    dir
}

fn touch(path: &Path, content: &str) {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).unwrap();
    }
    fs::write(path, content).unwrap();
}

fn node(id: &str, title: &str, file_path: &str, pinned: bool) -> serde_json::Value {
    json!({
        "id": id, "title": title, "role": "reference", "brief": "",
        "filePath": file_path, "readOrder": 0, "pinned": pinned,
        "position": { "x": 0, "y": 0 }
    })
}

fn edge(id: &str, source: &str, target: &str, kind: &str) -> serde_json::Value {
    json!({ "id": id, "source": source, "target": target, "kind": kind })
}

fn graph_json(project_name: &str, nodes: &[serde_json::Value], edges: &[serde_json::Value]) -> String {
    json!({
        "version": 3, "projectName": project_name,
        "nodes": nodes, "edges": edges, "compileTargets": ["agents", "cursor"]
    })
    .to_string()
}

/// Writes `.cowtext/tasklinks.json` directly (taskctx.rs reads it via
/// `tasklinks::tasklinks_read`, so this helper has no dependency on
/// `tasklinks::tasklink_set`).
fn write_tasklinks(dir: &Path, links: &[serde_json::Value]) {
    let doc = json!({ "version": 1, "links": links });
    touch(
        &dir.join(".cowtext/tasklinks.json"),
        &serde_json::to_string_pretty(&doc).unwrap(),
    );
}

fn link(task_id: &str, node_ids: &[&str]) -> serde_json::Value {
    json!({ "taskId": task_id, "nodeIds": node_ids, "sessionIds": [] })
}

fn link_with_parent(task_id: &str, node_ids: &[&str], parent: &str) -> serde_json::Value {
    json!({ "taskId": task_id, "nodeIds": node_ids, "sessionIds": [], "parentTaskId": parent })
}

fn preview(root: &Path, task_id: &str, graph: &str) -> TaskContext {
    task_context_preview(root.to_string_lossy().into_owned(), task_id.to_string(), graph.to_string())
        .unwrap()
}

